import { Link, useRouterState } from '@tanstack/react-router'
import { useAppStore } from '@/store/app.store'
import { supabase } from '@/lib/supabase'
import { cn } from '@/lib/utils'

const navItems = [
  { to: '/', label: 'Dashboard', icon: HomeIcon, exact: true },
  { to: '/dogs', label: 'Kartotéka psů', icon: DogIcon },
  { to: '/owners', label: 'Majitelé', icon: PersonIcon },
  { to: '/calendar', label: 'Kalendář', icon: CalendarIcon },
  { to: '/stays', label: 'Termíny', icon: StaysIcon },
  { to: '/finance', label: 'Finance', icon: FinanceIcon },
  { to: '/settings', label: 'Nastavení', icon: SettingsIcon },
]

export function Sidebar() {
  const pathname = useRouterState({ select: (s) => s.location.pathname })
  const { darkMode, toggleDarkMode, sidebarOpen, setSidebarOpen } = useAppStore()

  const handleLogout = async () => {
    await supabase.auth.signOut()
  }

  return (
    <>
      {sidebarOpen && (
        <div
          className="fixed inset-0 z-30 bg-black/40 md:hidden"
          onClick={() => setSidebarOpen(false)}
        />
      )}
      <aside
        className={cn(
          'fixed inset-y-0 left-0 z-40 flex w-64 flex-col bg-white border-r border-gray-200 transition-transform duration-200 dark:bg-gray-900 dark:border-gray-700',
          'md:translate-x-0 md:static md:z-auto',
          sidebarOpen ? 'translate-x-0' : '-translate-x-full'
        )}
      >
        <div className="flex items-center gap-3 px-5 py-5 border-b border-gray-200 dark:border-gray-700">
          <span className="text-2xl">🐾</span>
          <span className="text-lg font-bold text-gray-900 dark:text-gray-100">Dogoteka</span>
        </div>

        <nav className="flex-1 overflow-y-auto px-3 py-4 space-y-1">
          {navItems.map(({ to, label, icon: Icon, exact }) => {
            const active = exact ? pathname === to : pathname.startsWith(to)
            return (
              <Link
                key={to}
                to={to}
                onClick={() => setSidebarOpen(false)}
                className={cn(
                  'flex items-center gap-3 rounded-lg px-3 py-2.5 text-sm font-medium transition-colors',
                  active
                    ? 'bg-brand-50 text-brand-700 dark:bg-brand-900/30 dark:text-brand-300'
                    : 'text-gray-600 hover:bg-gray-100 hover:text-gray-900 dark:text-gray-400 dark:hover:bg-gray-800 dark:hover:text-gray-100'
                )}
              >
                <Icon className="size-5 shrink-0" />
                {label}
              </Link>
            )
          })}
        </nav>

        <div className="border-t border-gray-200 dark:border-gray-700 px-3 py-4 space-y-1">
          <button
            onClick={toggleDarkMode}
            className="flex w-full items-center gap-3 rounded-lg px-3 py-2.5 text-sm font-medium text-gray-600 hover:bg-gray-100 dark:text-gray-400 dark:hover:bg-gray-800 transition-colors"
          >
            {darkMode ? <SunIcon className="size-5" /> : <MoonIcon className="size-5" />}
            {darkMode ? 'Světlý režim' : 'Tmavý režim'}
          </button>
          <button
            onClick={handleLogout}
            className="flex w-full items-center gap-3 rounded-lg px-3 py-2.5 text-sm font-medium text-red-600 hover:bg-red-50 dark:text-red-400 dark:hover:bg-red-900/20 transition-colors"
          >
            <LogoutIcon className="size-5" />
            Odhlásit se
          </button>
        </div>
      </aside>
    </>
  )
}

